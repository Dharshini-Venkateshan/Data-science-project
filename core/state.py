"""
State management module for Autonomous AI Data Scientist.
Defines strongly-typed Pydantic v2 data models for the multi-agent framework.
"""

from typing import Dict, List, Optional, Any, Literal
from pydantic import BaseModel, Field


class ColumnMetadata(BaseModel):
    """Metadata describing a single dataset column."""
    name: str
    dtype: str
    inferred_type: Literal[
        "numeric_continuous",
        "numeric_discrete",
        "categorical_nominal",
        "categorical_ordinal",
        "datetime",
        "text",
        "identifier",
        "unknown"
    ] = "unknown"
    missing_count: int = 0
    missing_percentage: float = 0.0
    unique_count: int = 0
    sample_values: List[Any] = Field(default_factory=list)
    notes: Optional[str] = None


class DataProfile(BaseModel):
    """Holistic dataset profile generated by Data Analyst Agent."""
    row_count: int
    col_count: int
    columns: Dict[str, ColumnMetadata] = Field(default_factory=dict)
    target_column: Optional[str] = None
    problem_type: Literal[
        "binary_classification",
        "multiclass_classification",
        "regression",
        "time_series",
        "clustering",
        "unknown"
    ] = "unknown"
    class_imbalance_ratio: Optional[float] = None
    duplicate_rows_count: int = 0
    constant_columns: List[str] = Field(default_factory=list)
    potential_leakage_columns: List[str] = Field(default_factory=list)
    high_cardinality_columns: List[str] = Field(default_factory=list)
    skewed_numeric_columns: List[str] = Field(default_factory=list)


class ExecutionPlan(BaseModel):
    """Dynamic plan synthesized by Planner Agent."""
    target_column: str
    problem_type: str
    primary_metric: str
    secondary_metrics: List[str] = Field(default_factory=list)
    hypotheses: List[str] = Field(default_factory=list)
    agent_sequence: List[str] = Field(default_factory=list)
    status: Literal["PLANNED", "IN_PROGRESS", "COMPLETED", "REVISED"] = "PLANNED"
    iteration_notes: Optional[str] = None


class CleaningArtifact(BaseModel):
    """Output from Data Cleaning Agent."""
    code: str
    transformations_applied: List[str] = Field(default_factory=list)
    dropped_columns: List[str] = Field(default_factory=list)
    train_shape: Optional[List[int]] = None
    val_shape: Optional[List[int]] = None
    test_shape: Optional[List[int]] = None
    clean_train_path: Optional[str] = None
    clean_val_path: Optional[str] = None
    clean_test_path: Optional[str] = None
    leakage_guard_passed: bool = False
    notes: Optional[str] = None


class EDAResults(BaseModel):
    """Exploratory Data Analysis artifact."""
    top_correlations: List[Dict[str, Any]] = Field(default_factory=list)
    mutual_info_scores: Dict[str, float] = Field(default_factory=dict)
    generated_chart_paths: List[str] = Field(default_factory=list)
    statistical_anomalies: List[str] = Field(default_factory=list)
    key_findings: List[str] = Field(default_factory=list)


class FeatureArtifact(BaseModel):
    """Output from Feature Engineering Agent."""
    code: str
    engineered_feature_names: List[str] = Field(default_factory=list)
    dropped_feature_names: List[str] = Field(default_factory=list)
    selection_method: Optional[str] = None
    total_features_count: int = 0
    engineered_train_path: Optional[str] = None
    engineered_val_path: Optional[str] = None
    engineered_test_path: Optional[str] = None
    notes: Optional[str] = None


class ModelEvaluationMetric(BaseModel):
    """Detailed metrics for a single evaluation dimension."""
    metric_name: str
    train_score: Optional[float] = None
    val_score: Optional[float] = None
    test_score: Optional[float] = None
    cv_mean: Optional[float] = None
    cv_std: Optional[float] = None
    bootstrap_ci_lower: Optional[float] = None
    bootstrap_ci_upper: Optional[float] = None


class TrainedModelCandidate(BaseModel):
    """Checkpoint and evaluation metrics for a single model candidate."""
    model_name: str
    algorithm: str
    hyperparameters: Dict[str, Any] = Field(default_factory=dict)
    metrics: Dict[str, ModelEvaluationMetric] = Field(default_factory=dict)
    is_champion: bool = False
    artifact_path: Optional[str] = None


class EvaluationReport(BaseModel):
    """Comprehensive tournament results from Evaluation Agent."""
    leaderboard: List[TrainedModelCandidate] = Field(default_factory=list)
    champion_model_name: Optional[str] = None
    generalization_gap: Optional[float] = None
    cv_variance: Optional[float] = None
    calibration_brier_score: Optional[float] = None
    expected_calibration_error: Optional[float] = None
    confusion_matrix: Optional[List[List[int]]] = None
    classification_report: Optional[Dict[str, Any]] = None
    residual_diagnostics: Optional[Dict[str, Any]] = None


class CriticAuditItem(BaseModel):
    """Single diagnostic vector check conducted by Critic Agent."""
    vector_id: int = Field(ge=1, le=8, description="Vector ID 1 to 8")
    check_name: str
    status: Literal["PASS", "WARNING", "CRITICAL_FAIL"]
    observation: str
    recommendation: str
    affected_component: str = ""                            # Pipeline component affected
    evidence: Dict[str, Any] = Field(default_factory=dict) # Structured numeric evidence


class CriticFeedback(BaseModel):
    """Adversarial evaluation decision and actionable instructions from Critic Agent."""
    verdict: Literal["APPROVED", "REJECTED"]
    health_score: float = Field(ge=0.0, le=100.0, description="Overall pipeline health score")
    iteration: int = 1
    audit_results: List[CriticAuditItem] = Field(default_factory=list)
    target_agent_to_rerun: Optional[Literal[
        "DataCleaner", "FeatureEngineer", "ModelTrainer", "Evaluator"
    ]] = None
    specific_directives: str = ""


class ReflectionCycleLog(BaseModel):
    """
    Full record of one self-reflection audit cycle.
    Enables scientific auditability of every decision the orchestrator makes.
    """
    cycle_number: int
    verdict: Literal["APPROVED", "REJECTED"]
    health_score: float
    critical_issues: List[str] = Field(default_factory=list)
    warnings_raised: List[str] = Field(default_factory=list)
    corrective_action: Optional[str] = None
    agent_rerun: Optional[str] = None
    champion_before: Optional[str] = None
    champion_after: Optional[str] = None
    metrics_before: Dict[str, float] = Field(default_factory=dict)
    metrics_after: Dict[str, float] = Field(default_factory=dict)
    directive_summary: str = ""
    stopped_reason: Optional[str] = None   # "APPROVED" | "MAX_ITERATIONS_REACHED"


class InsightArtifact(BaseModel):
    """Output from Insight / XAI Agent (Explainability & Domain Analysis)."""
    global_feature_importance: Dict[str, float] = Field(default_factory=dict)
    feature_importance_plot_path: Optional[str] = None
    shap_summary_plot_path: Optional[str] = None
    explanation_method: str = "SHAP"  # "TreeSHAP" | "LinearCoefficients" | "PermutationImportance"
    champion_model_name: Optional[str] = None
    local_case_explanations: List[Dict[str, Any]] = Field(default_factory=list)
    vulnerability_warnings: List[str] = Field(default_factory=list)
    business_recommendations: List[str] = Field(default_factory=list)
    summary_text: Optional[str] = None


class DataScienceState(BaseModel):
    """
    Central shared state of the Autonomous Data Scientist framework.
    Passed between nodes and agents with strict Pydantic v2 validation.
    """
    session_id: str
    user_goal: str
    raw_dataset_path: str
    
    # Iteration & Control
    current_iteration: int = 1
    max_iterations: int = 3
    status: Literal[
        "INITIALIZED",
        "PROFILING",
        "PLANNING",
        "CLEANING",
        "EDA",
        "FEATURE_ENGINEERING",
        "MODELING",
        "EVALUATING",
        "CRITIC_REVIEW",
        "RE_PLANNING",
        "EXPLAINING",
        "REPORTING",
        "COMPLETED",
        "FAILED"
    ] = "INITIALIZED"

    # Agent Artifacts
    profile: Optional[DataProfile] = None
    plan: Optional[ExecutionPlan] = None
    cleaning_artifact: Optional[CleaningArtifact] = None
    eda_results: Optional[EDAResults] = None
    feature_artifact: Optional[FeatureArtifact] = None
    evaluation_report: Optional[EvaluationReport] = None
    champion_model_name: Optional[str] = None
    critic_history: List[CriticFeedback] = Field(default_factory=list)
    insight_artifact: Optional[InsightArtifact] = None
    final_report_path: Optional[str] = None

    # Phase 4: Self-Reflection & Closed-Loop Orchestration
    reflection_log: List[ReflectionCycleLog] = Field(default_factory=list)
    critic_directives: Dict[str, Any] = Field(default_factory=dict)  # Machine-readable corrective directives

    # Telemetry and Execution Logs
    execution_logs: List[str] = Field(default_factory=list)
    error_message: Optional[str] = None

    def log(self, message: str) -> None:
        """Appends a timestamped log entry to state."""
        self.execution_logs.append(message)
